export function getLocalizedPricingData(isBengali: boolean) {
  if (!isBengali) {
    return {
      serviceCharges: SERVICE_CHARGES,
      softwarePricing: SOFTWARE_INDIVIDUAL_PRICING,
      pricingTiers: PRICING_TIERS,
    };
  }
  return {
    serviceCharges: SERVICE_CHARGES.map((item) => ({
      ...item,
      ...(SERVICE_CHARGES_BN[item.id] || {}),
    })),
    softwarePricing: SOFTWARE_INDIVIDUAL_PRICING.map((item) => {
      const sw = SOFTWARE_PRODUCTS.find((p) => p.demoTabKey === item.demoTabKey);
      const swBn = sw ? SOFTWARE_BN[sw.id] : undefined;
      return {
        ...item,
        ...(PRODUCT_PRICING_BN[item.id] || {}),
        features: swBn?.features || item.features,
      };
    }),
    pricingTiers: PRICING_TIERS.map((tier) => ({
      ...tier,
      ...(PRICING_TIERS_BN[tier.id] || {}),
    })),
  };
}

