export function localizeCourse(course: TrainingCourse, isBengali: boolean): TrainingCourse {
  if (!isBengali) return course;
  const bn = COURSES_BN[course.id];
  if (!bn) return course;
  return { ...course, ...bn };
}

export function getLocalizedTrainingCourses(isBengali: boolean): TrainingCourse[] {
  return TRAINING_COURSES.map((c) => localizeCourse(c, isBengali));
}

